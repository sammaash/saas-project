"""Build ONE atomic SQL script that removes every tenant while keeping the platform foundation.

What it removes
    Every row of ``public.tenants`` and, through the schema's ``ON DELETE CASCADE`` foreign
    keys, every tenant-owned row: channels, members, settings, subscriptions, catalogue,
    customers, conversations, messages, orders, quotations, handovers, webhook events,
    credential-vault rows.

What it keeps
    ``plans``, ``platform_admins``, ``reserved_phone_numbers``, ``platform_user_directory`` (0042;
    it has no ``tenant_id``), the migration ledger, every
    role, grant, function and policy, and **all of** ``audit_log``: its tenant foreign key is
    ``ON DELETE SET NULL``, so history survives; the original tenant attribution of each audit
    row is preserved in the backup schema. Supabase ``auth.users`` is not touched.

Recoverability
    Before deleting, the script copies every affected row (each public table that has a
    ``tenant_id`` column, ``tenants`` itself, and the audit-row -> tenant links) into a new
    schema that no application role can reach. Restoring is ``insert ... select`` from it.

Guards
    * the caller must be able to bypass RLS (superuser or BYPASSRLS), otherwise RLS could make
      the copy and delete silently partial;
    * the number of tenants must equal ``--expect-tenants`` (taken from a read-only inventory
      immediately beforehand), and the backup schema must not already exist;
    * afterwards every tenant table must be empty, every backup table must hold exactly the
      rows that were removed, and the platform tables must be unchanged -- otherwise the whole
      transaction is rolled back.

Usage::

    python db/build_tenant_reset.py --expect-tenants 1 --backup-schema tenant_reset_backup_20261116
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PLATFORM_TABLES = ("plans", "platform_admins", "reserved_phone_numbers", "saas_schema_migrations")


def build_reset(expect_tenants: int, backup_schema: str) -> str:
    if expect_tenants < 0:
        raise ValueError("--expect-tenants must be zero or more")
    if not re.fullmatch(r"tenant_reset_backup_[0-9a-z_]{1,40}", backup_schema):
        raise ValueError("--backup-schema must look like tenant_reset_backup_<yyyymmdd>")
    platform_counts = ",\n    ".join(
        f"('{t}', (select count(*) from public.{t}))" for t in PLATFORM_TABLES
    )
    return f"""-- Generated by db/build_tenant_reset.py -- do not edit by hand.
-- Removes all {expect_tenants} tenant(s) and their data; keeps the platform foundation and audit history.
-- Backup of every removed row: schema {backup_schema}. Single transaction.

begin;

set local lock_timeout = '15s';

do $guard$
begin
  if not (select rolsuper or rolbypassrls from pg_catalog.pg_roles where rolname = current_user) then
    raise exception 'tenant reset must run as a role that bypasses RLS (current_user=%)', current_user;
  end if;
  if to_regnamespace('{backup_schema}') is not null then
    raise exception 'backup schema {backup_schema} already exists; refusing to overwrite it';
  end if;
  if (select count(*) from public.tenants) <> {expect_tenants} then
    raise exception 'expected {expect_tenants} tenant(s), found %; nothing changed',
      (select count(*) from public.tenants);
  end if;
end
$guard$;

create schema {backup_schema};
revoke all on schema {backup_schema} from public;
comment on schema {backup_schema} is
  'Rows removed by the tenant reset (db/build_tenant_reset.py). No application role has access.';

create table {backup_schema}._platform_counts_before as
  select * from (values
    {platform_counts}
  ) as t(table_name, row_count);

create table {backup_schema}._audit_tenant_links as
  select id as audit_log_id, tenant_id from public.audit_log where tenant_id is not null;

create table {backup_schema}._removed_counts (table_name text primary key, row_count bigint not null);

do $backup$
declare
  t text;
  n bigint;
begin
  for t in
    select c.relname
      from pg_catalog.pg_class c
     where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
       and c.relname <> 'audit_log'
       and (c.relname = 'tenants' or exists (
             select 1 from pg_catalog.pg_attribute a
              where a.attrelid = c.oid and a.attname = 'tenant_id' and not a.attisdropped))
     order by c.relname
  loop
    execute format('create table {backup_schema}.%I as table public.%I', t, t);
    execute format('select count(*) from {backup_schema}.%I', t) into n;
    insert into {backup_schema}._removed_counts values (t, n);
  end loop;
end
$backup$;

delete from public.tenants;

insert into public.audit_log (tenant_id, actor_user_id, actor_type, action, entity_type, entity_id, metadata)
select null, null, 'platform', 'platform.tenant_reset', 'tenant', null,
       jsonb_build_object(
         'tenants_removed', {expect_tenants},
         'backup_schema', '{backup_schema}',
         'removed_rows', (select jsonb_object_agg(table_name, row_count) from {backup_schema}._removed_counts),
         'audit_rows_detached', (select count(*) from {backup_schema}._audit_tenant_links)
       );

do $postcondition$
declare
  r record;
  n bigint;
begin
  for r in select table_name from {backup_schema}._removed_counts loop
    execute format('select count(*) from public.%I', r.table_name) into n;
    if n <> 0 then
      raise exception 'public.% still holds % row(s) after the reset', r.table_name, n;
    end if;
  end loop;
  for r in select table_name, row_count from {backup_schema}._platform_counts_before loop
    execute format('select count(*) from public.%I', r.table_name) into n;
    if n <> r.row_count then
      raise exception 'platform table public.% changed (% -> %)', r.table_name, r.row_count, n;
    end if;
  end loop;
  if exists (select 1 from public.audit_log a join {backup_schema}._audit_tenant_links l
               on l.audit_log_id = a.id where a.tenant_id is not null) then
    raise exception 'audit rows still reference removed tenants';
  end if;
  if (select count(*) from public.audit_log a join {backup_schema}._audit_tenant_links l
        on l.audit_log_id = a.id) <> (select count(*) from {backup_schema}._audit_tenant_links) then
    raise exception 'audit history was lost';
  end if;
  for r in select rolname from pg_catalog.pg_roles
            where rolname in ('anon', 'authenticated', 'authenticator', 'service_role',
                              'app_backend', 'saas_platform_admin', 'saas_platform_provisioner') loop
    if has_schema_privilege(r.rolname, '{backup_schema}', 'USAGE') then
      raise exception 'role % can reach the backup schema', r.rolname;
    end if;
  end loop;
end
$postcondition$;

commit;
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--expect-tenants", type=int, required=True)
    parser.add_argument("--backup-schema", required=True)
    parser.add_argument("--output")
    args = parser.parse_args(argv)
    try:
        script = build_reset(args.expect_tenants, args.backup_schema)
    except ValueError as error:
        parser.error(str(error))
    if args.output:
        Path(args.output).write_text(script, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(script)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
