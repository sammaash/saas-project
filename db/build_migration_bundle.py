"""Build ONE atomic SQL script that applies pending migrations exactly as run_migrations.py does.

Why this exists
---------------
``run_migrations.py`` deliberately refuses Supabase targets, and the production database is not
reachable from an operator workstation. Production is therefore migrated by pasting a script
into the Supabase SQL editor, which runs as the project's non-superuser ``postgres`` role. A
hand-assembled paste is error-prone (wrong file, edited text, missing ledger row, forgotten
provisioner release), so this tool generates the script from the repository files and the
script defends itself:

* PRECONDITION -- the ledger must contain exactly the expected versions with exactly the
  expected checksums (the repository files up to ``--applied-through``). Anything else aborts
  before a single statement runs: a database that is ahead, behind, or drifted is refused.
* The provisioner elevation is the runner's ``ensure_provisioner_access``: a temporary
  ``grant saas_platform_provisioner to current_user with inherit true, set true`` when the
  caller is not a superuser and lacks USAGE+SET, released with ``revoke`` afterwards.
* Each migration file is embedded verbatim and followed by its ledger row, with the same
  checksum function the runner uses (``sha256(text)[:16]``).
* POSTCONDITION -- the ledger holds exactly the expected rows, the temporary membership is gone
  and the provisioner holds no CREATE on schema ``app``; otherwise everything is rolled back.
* The whole script is a single transaction: it either commits completely or changes nothing.

Usage::

    python db/build_migration_bundle.py --applied-through 0037_quotation_briefs_and_deliveries.sql \
        --output bundle.sql

The output contains no credentials. ``tests/test_migration_0038_pg17_nonsuperuser.py`` applies a
generated bundle to a PostgreSQL 17 cluster with the production role model and compares the
result with the runner's.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from db.run_migrations import LEDGER_SQL, MIGRATIONS_DIR, PROVISIONER_ROLE, _checksum, _sql_files


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _dollar_tag(body: str, base: str) -> str:
    tag = base
    while f"${tag}$" in body:
        tag += "_"
    return f"${tag}$"


def build_bundle(applied_through: str, through: str | None = None,
                 directory: Path = MIGRATIONS_DIR) -> str:
    files = _sql_files(directory)
    names = [path.name for path in files]
    if applied_through not in names:
        raise ValueError(f"{applied_through} is not a migration file in {directory}")
    if through is not None and through not in names:
        raise ValueError(f"{through} is not a migration file in {directory}")

    texts = {path.name: path.read_text(encoding="utf-8") for path in files}
    applied = [name for name in names if name <= applied_through]
    pending = [name for name in names if name > applied_through and (through is None or name <= through)]
    if not pending:
        raise ValueError("nothing to apply")
    expected_after = applied + pending

    def values(rows: list[str]) -> str:
        return ",\n    ".join(f"({_literal(n)}, {_literal(_checksum(texts[n]))})" for n in rows)

    out: list[str] = []
    out.append(
        "-- Generated by db/build_migration_bundle.py -- do not edit by hand.\n"
        f"-- Expected ledger before: {len(applied)} rows, through {applied_through}\n"
        f"-- Applies: {', '.join(pending)}\n"
        "-- Single transaction: commits completely or changes nothing.\n"
    )
    for name in pending:
        out.append(f"--   {name}  checksum {_checksum(texts[name])}\n")
    out.append("\nbegin;\n\nset local lock_timeout = '15s';\n\n")

    out.append(LEDGER_SQL.strip().rstrip(";") + ";\n\n")
    out.append(
        "-- PRECONDITION: the ledger is exactly the expected set with exactly the expected checksums.\n"
        "do $precondition$\n"
        "declare problems text;\n"
        "begin\n"
        "  with expected(version, checksum) as (values\n    " + values(applied) + "\n  )\n"
        "  select string_agg(coalesce(e.version, l.version) || ' expected=' || coalesce(e.checksum, '<none>')\n"
        "                    || ' recorded=' || coalesce(l.checksum, '<none>'), '; ')\n"
        "    into problems\n"
        "    from expected e full join public.saas_schema_migrations l on l.version = e.version\n"
        "   where e.checksum is distinct from l.checksum;\n"
        "  if problems is not null then\n"
        "    raise exception 'ledger precondition failed, nothing applied: %', problems;\n"
        "  end if;\n"
        "end\n"
        "$precondition$;\n\n"
    )
    out.append(
        "-- Temporary provisioner elevation (run_migrations.ensure_provisioner_access).\n"
        "do $elevate$\n"
        "begin\n"
        f"  if not exists (select 1 from pg_catalog.pg_roles where rolname = {_literal(PROVISIONER_ROLE)}) then\n"
        f"    raise exception 'role {PROVISIONER_ROLE} is missing';\n"
        "  end if;\n"
        "  if (select rolsuper from pg_catalog.pg_roles where rolname = current_user)\n"
        f"     or (pg_catalog.pg_has_role(current_user, {_literal(PROVISIONER_ROLE)}, 'USAGE')\n"
        f"         and pg_catalog.pg_has_role(current_user, {_literal(PROVISIONER_ROLE)}, 'SET')) then\n"
        "    perform set_config('saas.bundle_elevated', 'off', true);\n"
        "  else\n"
        f"    execute 'grant {PROVISIONER_ROLE} to current_user with inherit true, set true';\n"
        "    perform set_config('saas.bundle_elevated', 'on', true);\n"
        "  end if;\n"
        "end\n"
        "$elevate$;\n\n"
    )
    for name in pending:
        text = texts[name]
        out.append(f"-- ===== BEGIN {name} =====\n")
        out.append(text if text.endswith("\n") else text + "\n")
        out.append(f"-- ===== END {name} =====\n")
        out.append(
            "insert into public.saas_schema_migrations (version, checksum) values "
            f"({_literal(name)}, {_literal(_checksum(text))});\n\n"
        )
    out.append(
        "-- Release the temporary elevation (run_migrations.release_provisioner_access).\n"
        "do $release$\n"
        "begin\n"
        "  if current_setting('saas.bundle_elevated', true) = 'on' then\n"
        f"    execute 'revoke {PROVISIONER_ROLE} from current_user';\n"
        "  end if;\n"
        "end\n"
        "$release$;\n\n"
    )
    out.append(
        "-- POSTCONDITION: exact ledger, no residual elevation, no residual CREATE on schema app.\n"
        "do $postcondition$\n"
        "declare problems text;\n"
        "begin\n"
        "  with expected(version, checksum) as (values\n    " + values(expected_after) + "\n  )\n"
        "  select string_agg(coalesce(e.version, l.version), ', ')\n"
        "    into problems\n"
        "    from expected e full join public.saas_schema_migrations l on l.version = e.version\n"
        "   where e.checksum is distinct from l.checksum;\n"
        "  if problems is not null then\n"
        "    raise exception 'ledger postcondition failed: %', problems;\n"
        "  end if;\n"
        "  if current_setting('saas.bundle_elevated', true) = 'on' and exists (\n"
        "       select 1 from pg_catalog.pg_auth_members\n"
        f"        where roleid = {_literal(PROVISIONER_ROLE)}::regrole\n"
        "          and member = current_user::regrole and grantor = current_user::regrole) then\n"
        "    raise exception 'temporary provisioner membership was not released';\n"
        "  end if;\n"
        f"  if has_schema_privilege({_literal(PROVISIONER_ROLE)}, 'app', 'CREATE') then\n"
        "    raise exception 'provisioner still holds CREATE on schema app';\n"
        "  end if;\n"
        "end\n"
        "$postcondition$;\n\n"
        "commit;\n"
    )
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--applied-through", required=True,
                        help="last migration file the target ledger already records")
    parser.add_argument("--through", help="last migration file to apply (default: newest)")
    parser.add_argument("--output", help="write the bundle here instead of stdout")
    args = parser.parse_args(argv)
    try:
        bundle = build_bundle(args.applied_through, args.through)
    except ValueError as error:
        parser.error(str(error))
    if args.output:
        Path(args.output).write_text(bundle, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(bundle)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
